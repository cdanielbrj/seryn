import { test, expect } from '@playwright/test'

test('acesso, layout v2, temas, navegação e saída', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Bem-vindo à Seryn' })).toBeVisible()
  await page.getByLabel('Usuário', { exact: true }).fill('e2e')
  await page.getByLabel('Senha', { exact: true }).fill('Seryn teste descartavel 123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Visão Geral' })).toBeVisible()
  await expect(page.getByText('Nenhum registro por aqui')).toBeVisible()
  await expect(page.locator('.stat-value')).toHaveText(['—', '—', '—'])

  const mobile = testInfo.project.name.includes('mobile')
  const nav = page.getByRole('navigation', { name: mobile ? 'Navegação mobile' : 'Navegação principal', exact: true })
  await expect(nav).toBeVisible()
  if (mobile) {
    await expect(page.getByText('Resultado previsto', { exact: true })).toBeVisible()
    await expect(page.locator('.projection-panel')).toBeHidden()
    const result = await page.locator('.stat.result').boundingBox()
    const income = await page.locator('.stat.income').boundingBox()
    expect(result!.y).toBeLessThan(income!.y)
    await page.getByRole('link', { name: 'Ver todos' }).click()
    await expect(page.getByRole('heading', { name: 'Registros', exact: true })).toBeVisible()
    await nav.getByRole('link', { name: 'Visão Geral' }).click()
  } else {
    for (const title of ['Projeção do período', 'Por categoria', 'Registros previstos'])
      await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)

  await page.getByRole('button', { name: 'Semestre', exact: true }).click()
  const oldPeriod = await page.locator('.date-select span').innerText()
  await page.getByRole('button', { name: 'Próximo período' }).click()
  await expect(page.locator('.date-select span')).not.toHaveText(oldPeriod)
  await page.getByRole('button', { name: 'Mês', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('overview-light.png'), fullPage: true })
  await page.getByRole('button', { name: 'Ativar tema escuro' }).filter({ visible: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Visão Geral' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: testInfo.outputPath('overview-dark.png'), fullPage: true })

  if (!mobile) {
    await nav.getByRole('link', { name: 'Pagamentos', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Pagamentos', exact: true })).toBeVisible()
    await page.getByLabel('Nome', { exact: true }).fill('Pix')
    await page.getByRole('button', { name: 'Adicionar', exact: true }).click()
    await expect(page.getByText('Pix', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Excluir Pix', exact: true }).click()
    await expect(page.getByRole('alertdialog', { name: 'Excluir pagamento?' })).toBeVisible()
    await page.getByRole('button', { name: 'Excluir pagamento', exact: true }).click()
    await expect(page.getByText('Nenhum pagamento cadastrado')).toBeVisible()
  }

  await nav.getByRole('link', { name: 'Categorias', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Categorias', exact: true })).toBeVisible()
  await page.getByLabel('Nome', { exact: true }).fill('Software')
  await page.getByRole('button', { name: 'Adicionar', exact: true }).click()
  await expect(page.getByText('Software', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Adicionar subcategoria em Software', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Streaming')
  await page.getByRole('button', { name: 'Adicionar', exact: true }).click()
  await expect(page.getByText('Streaming', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Software possui subcategorias e não pode ser excluída' })).toBeDisabled()
  await page.getByRole('button', { name: 'Excluir Streaming', exact: true }).click()
  await expect(page.getByRole('alertdialog', { name: 'Excluir subcategoria?' })).toBeVisible()
  await page.getByRole('button', { name: 'Excluir subcategoria', exact: true }).click()
  await expect(page.getByText('0 subcategorias')).toBeVisible()
  await page.getByRole('button', { name: 'Excluir Software', exact: true }).click()
  await expect(page.getByRole('alertdialog', { name: 'Excluir categoria?' })).toBeVisible()
  await page.getByRole('button', { name: 'Excluir categoria', exact: true }).click()
  await expect(page.getByText('Nenhuma categoria cadastrada')).toBeVisible()
  await nav.getByRole('link', { name: 'Ajustes', exact: true }).click()
  if (mobile) {
    await page.locator('.settings-links').getByRole('link', { name: 'Pagamentos', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Pagamentos', exact: true })).toBeVisible()
    await nav.getByRole('link', { name: 'Ajustes', exact: true }).click()
  }
  await page.locator('.settings-links').getByRole('link', { name: 'Tipos', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tipos', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Tipos', exact: true })).toBeVisible()
  await nav.getByRole('link', { name: 'Ajustes', exact: true }).click()
  await page.locator('.settings-links').getByRole('link', { name: 'Importar / Exportar' }).click()
  await expect(page.getByRole('heading', { name: 'Importar / Exportar', exact: true })).toBeVisible()
  await nav.getByRole('link', { name: 'Ajustes', exact: true }).click()
  await page.getByRole('combobox', { name: 'Aparência', exact: true }).selectOption('light')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Sair da Seryn' }).click()
  await expect(page.getByRole('heading', { name: 'Bem-vindo à Seryn' })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Bem-vindo à Seryn' })).toBeVisible()
  expect(await page.evaluate(async () => typeof caches === 'undefined' ? 0 : (await caches.keys()).length)).toBe(0)
  expect(errors).toEqual([])
})
